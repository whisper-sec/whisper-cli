func TestRouteServerTokenForms(t *testing.T) {
	for in, want := range map[string]string{
		rcOurs:                     rcOurs,
		strings.ToUpper(rcOurs):    rcOurs,
		rcOurs + "%2#dns.example":  rcOurs,
		"[" + rcOurs + "]:53":      rcOurs,
		"[" + rcOurs + "]:53#name": rcOurs,
		"192.0.2.1:53":             "192.0.2.1",
		"192.0.2.1#dns.example":    "192.0.2.1",
		"fe80::1%enp1s0":           "fe80::1",
	} {
		if got := stripServer(in); got != want {
			t.Fatalf("stripServer(%q) = %q, want %q", in, got, want)
		}
	}
	// An IPv6 server is never cut at its first colon by the scope parser.
	_, v := resolvedScopes("Global: " + rcOurs + " 192.0.2.1\nLink 2 (enp1s0):\n")
	if len(v["Global"]) != 2 || v["Global"][0] != rcOurs || len(v["Link 2 (enp1s0)"]) != 0 {
		t.Fatalf("scope parse wrong: %v", v)
	}
}

func TestRouteConfParserReadsOnlyResolveSection(t *testing.T) {
	got := confDNSLines("# DNS=192.0.2.9\n[Other]\nDNS=192.0.2.8\n[Resolve]\n; DNS=192.0.2.7\nDNS = 192.0.2.1 [2001:db8::1]:53\nDNS=\nFallbackDNS=192.0.2.6\n")
	if strings.Join(got, ",") != "192.0.2.1,2001:db8::1," {
		t.Fatalf("confDNSLines = %q", got)
	}
}

func TestRouteResolvConfFallbackCheck(t *testing.T) {
	if rc := CheckResolvConf(rcOurs, "nameserver "+rcOurs+"\nsearch example.com\n"); rc.State != RouteOurs {
		t.Fatalf("ours first: %+v", rc)
	}
	rc := CheckResolvConf(rcOurs, "nameserver 192.168.1.1\nnameserver "+rcOurs+"\n")
	if rc.State != RouteShadowed || !strings.Contains(rc.Problems[0], "192.168.1.1 first") {
		t.Fatalf("another server first means glibc asks it: %+v", rc)
	}
	if rc := CheckResolvConf(rcOurs, "# empty\n"); rc.State != RouteUnknown {
		t.Fatalf("no nameserver is unknown, not a pass: %+v", rc)
	}
}
