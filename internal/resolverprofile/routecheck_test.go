func TestRouteResolvConfBypassingResolved(t *testing.T) {
	ev := rcEvFixed
	ev.ResolvConf = "# Generated by NetworkManager\nnameserver 192.168.122.1\n"
	rc := CheckResolved(rcOurs, true, ev)
	if rc.State != RouteShadowed || !strings.Contains(strings.Join(rc.Problems, "\n"), "/etc/resolv.conf sends lookups straight to 192.168.122.1") {
		t.Fatalf("a resolv.conf that skips the stub bypasses resolved entirely: %+v", rc)
	}
	for _, ok := range []string{rcStub, "nameserver 127.0.0.54\n", "nameserver " + rcOurs + "\n", ""} {
		ev.ResolvConf = ok
		if rc := CheckResolved(rcOurs, true, ev); rc.State != RouteOurs {
			t.Fatalf("resolv.conf %q must not count as a bypass: %+v", ok, rc)
		}
	}
}

