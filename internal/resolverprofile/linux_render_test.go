func TestT2LinuxRevertIsUniversalAndGuarded(t *testing.T) {
	r := Profile{Mode: ModeDNS53, OS: "linux", ResolverIPs: []string{t2LinIP}}.Render(t2HostNoFwd)
	joined := ""
	for _, s := range r.Revert {
		joined += s.String() + "\n"
	}
	// One undo covers every apply shape: forwarder unit, dnscrypt config,
	// drop-in, resolv.conf backup - each behind its own presence guard.
	for _, want := range []string{
		"[if " + LinuxForwarderUnit + " exists] systemctl disable --now whisper-dns",
		"[if " + LinuxForwarderUnit + " exists] remove " + LinuxForwarderUnit,
		"[if " + LinuxDNSCryptConfig + " exists] remove " + LinuxDNSCryptConfig,
		"[if " + LinuxDropIn + " exists] remove " + LinuxDropIn,
		"[if " + LinuxDropIn + " exists] systemctl restart systemd-resolved",
		"[if " + LinuxResolvBackup + " exists] cp " + LinuxResolvBackup + " " + LinuxResolvConf,
		"[if " + LinuxResolvBackup + " exists] remove " + LinuxResolvBackup,
	} {
		if !strings.Contains(joined, want) {
			t.Fatalf("universal revert is missing %q:\n%s", want, joined)
		}
	}
}

func TestT2LinuxScriptCapturesPreStateGuards(t *testing.T) {
	// The rendered bash must evaluate guards BEFORE any step runs (the applier's
	// semantics): "restart resolved if the drop-in existed" still fires after an
	// earlier step removed the drop-in.
	r := Profile{Mode: ModeDoH, OS: "linux", DohTemplate: t2LinDoH}.Render(t2HostResolvedCF)
	script := r.RevertScript()
	if !strings.Contains(script, "# Pre-state guards (evaluated before any step runs).") {
		t.Fatalf("revert script must capture pre-state guards:\n%s", script)
	}
	// Guard capture lines precede the first guarded action.
	capIdx := strings.Index(script, "g0=0;")
	actIdx := strings.Index(script, "if [ \"$g0\" -eq 1 ]; then")
	if capIdx < 0 || actIdx < 0 || capIdx > actIdx {
		t.Fatalf("guard capture must precede its use:\n%s", script)
	}
	// set -e discipline plus the shebang: the block is directly runnable.
	if !strings.HasPrefix(script, "#!/usr/bin/env bash\n") || !strings.Contains(script, "set -euo pipefail") {
		t.Fatalf("script must be a strict, runnable bash block:\n%s", script)
	}
}

