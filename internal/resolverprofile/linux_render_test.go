func TestT2StepStringForms(t *testing.T) {
	cases := []struct {
		s    Step
		want string
	}{
		{Step{Cmd: []string{"systemctl", "daemon-reload"}}, "systemctl daemon-reload"},
		{Step{Remove: "/etc/x", IfPresent: "/etc/x"}, "[if /etc/x exists] remove /etc/x"},
		{Step{WaitFor: "127.0.0.1:53"}, "wait until 127.0.0.1:53 answers (bounded, 30s)"},
		{Step{Shell: "echo hi"}, "echo hi"},
		{Step{Cmd: []string{"echo", "two words"}}, "echo 'two words'"},
		{Step{}, "(no-op)"},
	}
	for _, c := range cases {
		if got := c.s.String(); got != c.want {
			t.Fatalf("Step.String() = %q, want %q", got, c.want)
		}
	}
}
