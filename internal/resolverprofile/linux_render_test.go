// The model-cluster tests for the LINUX side of the Tier-2 plan plus the
// OS-agnostic model itself: golden renders (the drop-in bytes, the forwarder
// unit, the dnscrypt stamp), the keyed/keyless forwarder fallback, the
// resolv.conf backup guards, and the pre-state guard semantics of the rendered
// scripts. Pure - they run on every build host.

const (
	t2LinDoH = "https://doh.whisper.online/tok_lin/dns-query"
	t2LinIP  = "2a04:2a01:0:53::42"
)

var (
	t2HostResolvedCF = Host{ResolvedActive: true, ForwarderKind: "cloudflared", ForwarderPath: "/usr/local/bin/cloudflared"}
	t2HostResolvedDC = Host{ResolvedActive: true, ForwarderKind: "dnscrypt-proxy", ForwarderPath: "/usr/bin/dnscrypt-proxy"}
	t2HostNoFwd      = Host{ResolvedActive: true}
)

func TestT2LinuxDNS53DropInGolden(t *testing.T) {
	r := Profile{Mode: ModeDNS53, OS: "linux", ResolverIPs: []string{t2LinIP}}.Render(t2HostNoFwd)
	if r.Mode != ModeDNS53 || r.OS != "linux" || r.ResolverIP != t2LinIP {
		t.Fatalf("rendered identity wrong: %+v", r)
	}
	if len(r.Apply) != 2 || r.Apply[0].File == nil {
		t.Fatalf("dns53 on resolved = drop-in + restart, got %v", r.Apply)
	}
	// The drop-in is byte-exact: the server template's shape (DNS= + Domains=~.).
	want := "# Whisper resolver - generated by `whisper resolver`; revert with `whisper resolver --off`.\n" +
		"[Resolve]\nDNS=" + t2LinIP + "\nDomains=~.\n"
	if got := r.Apply[0].File.Content; got != want {
		t.Fatalf("drop-in golden mismatch:\n--- got\n%s\n--- want\n%s", got, want)
	}
	if r.Apply[0].File.Path != LinuxDropIn {
		t.Fatalf("drop-in path = %q, want %q", r.Apply[0].File.Path, LinuxDropIn)
	}
	if got := r.Apply[1].String(); got != "systemctl restart systemd-resolved" {
		t.Fatalf("restart step = %q", got)
	}
	// The plaintext tradeoff is stated, never hidden (conservative out).
	if !strings.Contains(strings.Join(r.Notes, "\n"), "unencrypted") {
		t.Fatalf("dns53 notes must state the plaintext tradeoff: %v", r.Notes)
	}
}

func TestT2LinuxDNS53ResolvConfFallback(t *testing.T) {
	r := Profile{Mode: ModeDNS53, OS: "linux", ResolverIPs: []string{t2LinIP}}.Render(Host{ResolvedActive: false})
	if len(r.Apply) != 2 {
		t.Fatalf("dns53 without resolved = backup + write, got %v", r.Apply)
	}
	// Backup only when resolv.conf exists AND no backup exists yet (the server
	// script's discipline - never clobber the original backup).
	cp := r.Apply[0]
	if cp.IfPresent != LinuxResolvConf || cp.IfAbsent != LinuxResolvBackup {
		t.Fatalf("backup guards wrong: %+v", cp)
	}
	if cp.String() != "[if "+LinuxResolvConf+" exists] [if "+LinuxResolvBackup+" absent] cp "+LinuxResolvConf+" "+LinuxResolvBackup {
		t.Fatalf("backup step = %q", cp.String())
	}
	if r.Apply[1].File == nil || r.Apply[1].File.Path != LinuxResolvConf ||
		r.Apply[1].File.Content != "nameserver "+t2LinIP+"\n" {
		t.Fatalf("resolv.conf write wrong: %+v", r.Apply[1])
	}
}

func TestT2LinuxDoHCloudflaredGolden(t *testing.T) {
	r := Profile{Mode: ModeDoH, OS: "linux", DohTemplate: t2LinDoH}.Render(t2HostResolvedCF)
	// unit -> daemon-reload -> enable -> restart -> WAIT -> drop-in -> restart resolved
	if len(r.Apply) != 7 {
		t.Fatalf("cloudflared DoH plan should have 7 steps, got %d: %v", len(r.Apply), r.Apply)
	}
	unit := r.Apply[0]
	if unit.File == nil || unit.File.Path != LinuxForwarderUnit {
		t.Fatalf("first step must write the forwarder unit: %+v", unit)
	}
	for _, want := range []string{
		"ExecStart=/usr/local/bin/cloudflared proxy-dns --address 127.0.0.1 --port 53 --upstream " + t2LinDoH,
		"Restart=always",
		"WantedBy=multi-user.target",
	} {
		if !strings.Contains(unit.File.Content, want) {
			t.Fatalf("unit is missing %q:\n%s", want, unit.File.Content)
		}
	}
	// The bounded wait sits BETWEEN the forwarder start and the resolver
	// repoint - never leave DNS half-configured.
	if r.Apply[4].WaitFor != "127.0.0.1:53" {
		t.Fatalf("step 5 must wait for the forwarder, got %+v", r.Apply[4])
	}
	if r.Apply[5].File == nil || r.Apply[5].File.Path != LinuxDropIn ||
		!strings.Contains(r.Apply[5].File.Content, "DNS=127.0.0.1") {
		t.Fatalf("the drop-in must point resolved at the local forwarder: %+v", r.Apply[5])
	}
}

func TestT2LinuxDoHDnscryptStampGolden(t *testing.T) {
	r := Profile{Mode: ModeDoH, OS: "linux", DohTemplate: "https://doh.whisper.online/whisper_live_DEVICE_abc123/dns-query"}.Render(t2HostResolvedDC)
	toml := r.Apply[0]
	if toml.File == nil || toml.File.Path != LinuxDNSCryptConfig {
		t.Fatalf("dnscrypt DoH must write the TOML first: %+v", toml)
	}
	// Golden stamp, computed independently (protocol 0x02, zero props, empty
	// addr, empty hashes, LP(host), LP(path)) - byte-identical to the server's
	// the server's own DoH stamp.
	wantStamp := "sdns://AgAAAAAAAAAAAAASZG9oLndoaXNwZXIub25saW5lJS93aGlzcGVyX2xpdmVfREVWSUNFX2FiYzEyMy9kbnMtcXVlcnk"
	if !strings.Contains(toml.File.Content, "stamp = '"+wantStamp+"'") {
		t.Fatalf("dnscrypt TOML stamp golden mismatch:\n%s", toml.File.Content)
	}
	// The explicit bootstrap keeps the stamp's hostname resolvable without the
	// resolver being installed (no loop) - the server template's guard.
	if !strings.Contains(toml.File.Content, "bootstrap_resolvers = ['9.9.9.9:53', '1.1.1.1:53']") {
		t.Fatalf("dnscrypt TOML must carry the IP bootstrap:\n%s", toml.File.Content)
	}
}

