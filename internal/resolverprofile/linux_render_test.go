func TestT2DnscryptConfigVersionAdapts(t *testing.T) {
	// 2.1.0 renamed fallback_resolvers -> bootstrap_resolvers and BOTH lineages
	// FATAL on the other's key (proven live: stock Ubuntu 24.04's apt 2.0.45
	// exits "Unsupported key in configuration file: [bootstrap_resolvers]").
	cases := []struct{ version, wantKey string }{
		{"2.0.45", "fallback_resolvers"},
		{"2.0.45+ds1", "fallback_resolvers"},
		{"2.1.7", "bootstrap_resolvers"},
		{"2.1.14", "bootstrap_resolvers"},
		{"", "bootstrap_resolvers"},        // unknown -> modern
		{"garbage", "bootstrap_resolvers"}, // unparseable -> modern
	}
	for _, c := range cases {
		cfg := dnscryptConfig(t2LinDoH, c.version)
		if !strings.Contains(cfg, c.wantKey+" = ['9.9.9.9:53', '1.1.1.1:53']") {
			t.Fatalf("version %q must emit %s:\n%s", c.version, c.wantKey, cfg)
		}
		other := "bootstrap_resolvers"
		if c.wantKey == other {
			other = "fallback_resolvers"
		}
		if strings.Contains(cfg, other) {
			t.Fatalf("version %q must NOT emit %s (it fatals):\n%s", c.version, other, cfg)
		}
	}
}

func TestT2ForwarderVersionPolicy(t *testing.T) {
	// cloudflared removed proxy-dns in 2026.2.0 (proven live on 2026.8.2).
	for raw, removed := range map[string]bool{
		"cloudflared version 2026.8.2 (built 2026-08-14-12:17 UTC)": true,
		"cloudflared version 2026.2.0":                              true,
		"cloudflared version 2026.1.5 (built 2026-01-20)":           false, // 2026.1 still ships it
		"cloudflared version 2025.11.1":                             false,
		"":                                                          true, // unknown -> conservative: never install a crash-looping unit
		"garbage":                                                   true,
	} {
		if got := cloudflaredProxyDNSRemoved(raw); got != removed {
			t.Fatalf("cloudflaredProxyDNSRemoved(%q) = %v, want %v", raw, got, removed)
		}
	}
	// parseVersion is liberal in what it accepts.
	if v := parseVersion("dnscrypt-proxy 2.0.45"); len(v) != 3 || v[0] != 2 || v[1] != 0 || v[2] != 45 {
		t.Fatalf("parseVersion embedded = %v", v)
	}
	if v := parseVersion("built 2026 then 2.1.7 here"); len(v) != 3 || v[0] != 2 || v[1] != 1 || v[2] != 7 {
		t.Fatalf("parseVersion must skip lone numbers: %v", v)
	}
	if parseVersion("no digits at all") != nil {
		t.Fatalf("parseVersion must yield nil on no version")
	}
	if !versionAtLeast([]int{2, 1}, 2, 1) || versionAtLeast([]int{2, 0, 45}, 2, 1) || !versionAtLeast([]int{3}, 2, 1) {
		t.Fatalf("versionAtLeast comparisons wrong")
	}
}

